/* La bandera la sirve el backend desde la carpeta de la plantilla: es el
   mismo archivo que sale al aire, sin copiarlo dos veces. */
export const urlBandera = codigo =>
  codigo ? `/media/banderas/${String(codigo).toLowerCase()}.svg` : null

const POR_CODIGO = Object.fromEntries(PAISES.map(p => [p.codigo, p]))

export const paisDe = codigo =>
  codigo ? POR_CODIGO[String(codigo).toLowerCase()] || null : null

/* El nombre en el idioma del panel. Los dos vienen en la tabla en vez de
   pasar por el diccionario de i18n: son 255 y no son cadenas de interfaz,
   son datos. */
export const nombrePais = (codigo, idioma = "es") => {
  const p = paisDe(codigo)
  if (!p) return ""
  return idioma === "en" ? p.en : p.nombre
}
